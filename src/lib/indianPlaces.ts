export const ALL_INDIAN_STATES = INDIAN_STATES_AND_CITIES.map((item) => item.state);

export function getCitiesForState(stateName: string): string[] {
  if (!stateName) return [];
  const found = INDIAN_STATES_AND_CITIES.find(
    (item) => item.state.toLowerCase() === stateName.toLowerCase()
  );
  return found ? found.cities : [];
}

/**
 * Intelligent filter for states:
 * Prioritizes starts-with matching over contains matching.
 * E.g., typing 'Ta' prioritizes 'Tamil Nadu'.
 */
export function searchStates(query: string): string[] {
  const clean = query.trim().toLowerCase();
  if (!clean) return ALL_INDIAN_STATES;

  const startsWithList = ALL_INDIAN_STATES.filter((s) =>
    s.toLowerCase().startsWith(clean)
  );
  const containsList = ALL_INDIAN_STATES.filter(
    (s) => !s.toLowerCase().startsWith(clean) && s.toLowerCase().includes(clean)
  );

  return [...startsWithList, ...containsList];
}

/**
 * Intelligent filter for cities within a selected state:
 * Prioritizes starts-with matching over contains matching.
 * E.g., State = Tamil Nadu, typing 'Ch' prioritizes 'Chennai', 'Chengalpattu'.
 */
export function searchCities(stateName: string, query: string): string[] {
  const allCities = getCitiesForState(stateName);
  const clean = query.trim().toLowerCase();
  if (!clean) return allCities;

  const startsWithList = allCities.filter((c) =>
    c.toLowerCase().startsWith(clean)
  );
  const containsList = allCities.filter(
    (c) => !c.toLowerCase().startsWith(clean) && c.toLowerCase().includes(clean)
  );

  return [...startsWithList, ...containsList];
}
